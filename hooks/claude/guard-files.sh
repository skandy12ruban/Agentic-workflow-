#!/usr/bin/env bash
# Claude Code PreToolUse hook for file tools (Read, Edit, Write, MultiEdit, NotebookEdit, Grep, Glob).
#   - Blocks reading or writing secret/credential files.
#   - Blocks agents from modifying their own guardrails (hooks, settings, kill switch, git hooks).
#   - Blocks hand-editing lockfiles and .git internals.
#   - Blocks writes to project-specific protected paths listed in .agentic/protected-paths.
#   - Asks a human before CI/CD pipeline definitions are changed.
#   - Blocks writing content that contains credentials (API keys, tokens, private keys).
# Exit 2 = block (stderr shown to the agent). JSON "ask" = require human confirmation. Exit 0 = allow.
#
# Install: copy to .claude/hooks/guard-files.sh, chmod +x, register in .claude/settings.json:
#   "PreToolUse": [{ "matcher": "Read|Edit|Write|MultiEdit|NotebookEdit|Grep|Glob",
#                    "hooks": [{ "type": "command", "command": "\"$CLAUDE_PROJECT_DIR\"/.claude/hooks/guard-files.sh" }] }]
set -uo pipefail

input="$(cat)"
project_dir="${CLAUDE_PROJECT_DIR:-$PWD}"

json_field() {
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$input" | jq -r ".$1 // empty"
  elif command -v python3 >/dev/null 2>&1; then
    printf '%s' "$input" | python3 -c 'import json,sys
d=json.load(sys.stdin)
for k in sys.argv[1].split("."): d=d.get(k) if isinstance(d,dict) else None
print(d if isinstance(d,str) else "")' "$1"
  elif command -v node >/dev/null 2>&1; then
    printf '%s' "$input" | node -e 'let s="";process.stdin.on("data",c=>s+=c).on("end",()=>{let d=JSON.parse(s);for(const k of process.argv[1].split("."))d=d&&d[k];console.log(typeof d==="string"?d:"")})' "$1"
  else
    echo "BLOCKED by guardrails: guard-files needs jq, python3, or node." >&2; exit 2
  fi
}

block() {
  { echo "BLOCKED by guardrails: $1"
    echo "Do not work around this. If it is genuinely required, stop and ask the human."; } >&2
  exit 2
}
ask() {
  printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"ask","permissionDecisionReason":"%s"}}\n' "$1"
  exit 0
}

[[ -e "$project_dir/.agentic/STOP" ]] && block "kill switch is active (.agentic/STOP exists). Stop and report status to the human."

tool="$(json_field tool_name)" || { echo "BLOCKED by guardrails: could not parse hook input (fail closed)." >&2; exit 2; }
path="$(json_field tool_input.file_path)"
[[ -z "$path" ]] && path="$(json_field tool_input.notebook_path)"
[[ -z "$path" ]] && path="$(json_field tool_input.path)"
pattern_arg="$(json_field tool_input.pattern)"
glob_arg="$(json_field tool_input.glob)"

case "$tool" in Edit|Write|MultiEdit|NotebookEdit) writing=1 ;; *) writing=0 ;; esac

# Normalize to a path relative to the project when possible.
rel="${path#"$project_dir"/}"; rel="${rel#./}"
base="$(basename -- "${path:-x}")"

# ── 1. Secret / credential files (read AND write) ──────────────────────────────
is_secret_file() {
  local p="$1" b; b="$(basename -- "$p")"
  case "$b" in
    .env.example|.env.sample|.env.template|.env.dist|.env.defaults) return 1 ;;
    .env|.env.*|*.env) return 0 ;;
    id_rsa*|id_ed25519*|id_ecdsa*|id_dsa*|*.pem|*.key|*.p12|*.pfx|*.jks|*.keystore|*.kdbx) return 0 ;;
    credentials|credentials.json|*credentials*.json|service-account*.json|*.tfstate|*.tfstate.backup|.netrc|.npmrc|.pypirc|.htpasswd|secrets.y*ml|*.secret|*.secrets) return 0 ;;
  esac
  case "$p" in
    */.ssh/*|*/.aws/*|*/.gnupg/*|*/.kube/*|*/.docker/config.json|*/.config/gcloud/*|*/.azure/*|secrets/*|*/secrets/*) return 0 ;;
  esac
  return 1
}
if [[ -n "$path" ]] && is_secret_file "$path"; then
  block "'$rel' looks like a secret or credential file. Use .env.example / documented variable names instead."
fi
for g in "$pattern_arg" "$glob_arg"; do
  [[ "$tool" == "Glob" || "$tool" == "Grep" ]] || break
  case "$g" in *.env|*.env.\*|*.env\**|*id_rsa*|*.pem|*credentials*) block "searching secret files ('$g') is not allowed." ;; esac
done
[[ "$tool" == "Grep" && -n "$glob_arg" ]] && case "$glob_arg" in *.env*) [[ "$glob_arg" == *example* ]] || block "grepping .env files is not allowed." ;; esac

[[ $writing -eq 0 ]] && exit 0

# ── 2. Guardrails may not modify themselves ────────────────────────────────────
case "$rel" in
  .claude/hooks/*|.claude/settings.json|.claude/settings.local.json|.agentic/STOP|.agentic/guardrails.env|.agentic/protected-paths|.agentic/git-hooks/*|.git/hooks/*|.husky/*|.pre-commit-config.yaml|lefthook.yml|.lefthook.yml)
    block "'$rel' is part of the guardrails or git hooks. Only a human may change it." ;;
  .git/*|*/.git/*)
    block "do not edit .git internals; use git commands." ;;
esac

# ── 3. Lockfiles must be regenerated by the package manager ────────────────────
case "$base" in
  package-lock.json|npm-shrinkwrap.json|yarn.lock|pnpm-lock.yaml|bun.lockb|bun.lock|poetry.lock|uv.lock|Pipfile.lock|pdm.lock|Cargo.lock|Gemfile.lock|composer.lock|go.sum|mix.lock|pubspec.lock|Podfile.lock|packages.lock.json|gradle.lockfile)
    block "do not hand-edit '$base'; change the manifest and run the package manager." ;;
esac

# ── 4. Project-specific protected paths (.agentic/protected-paths, one glob per line) ──
pp="$project_dir/.agentic/protected-paths"
if [[ -f "$pp" ]]; then
  while IFS= read -r glob || [[ -n "$glob" ]]; do
    glob="${glob%%#*}"; glob="${glob%"${glob##*[![:space:]]}"}"; glob="${glob#"${glob%%[![:space:]]*}"}"
    [[ -z "$glob" ]] && continue
    # shellcheck disable=SC2053  # intentional glob match; '*' also matches '/'
    [[ "$rel" == $glob ]] && block "'$rel' matches protected path '$glob' (.agentic/protected-paths). Ask the human."
  done <"$pp"
fi

# ── 5. CI/CD definitions: human confirmation required ──────────────────────────
case "$rel" in
  .github/workflows/*|.github/actions/*|.gitlab-ci.yml|.gitlab/ci/*|azure-pipelines*.yml|.azure-pipelines/*|Jenkinsfile|.circleci/*|bitbucket-pipelines.yml|.buildkite/*|.drone.yml|.woodpecker.yml|.woodpecker/*|CODEOWNERS|.github/CODEOWNERS)
    ask "Agent wants to modify CI/CD or ownership config '$rel'. Approve only if the approved plan includes this change." ;;
esac

# ── 6. Credentials inside the content being written ────────────────────────────
# Fake keys in test fixtures: put "guardrails:allow-secret" on the same line.
secret_re='AKIA[0-9A-Z]{16}|ASIA[0-9A-Z]{16}|gh[pousr]_[A-Za-z0-9]{36,}|github_pat_[A-Za-z0-9_]{22,}|glpat-[A-Za-z0-9_-]{20,}|xox[abprs]-[A-Za-z0-9-]{10,}|sk-(ant-|proj-|live-)?[A-Za-z0-9_-]{32,}|sk_live_[0-9A-Za-z]{24,}|rk_live_[0-9A-Za-z]{24,}|AIza[0-9A-Za-z_-]{35}|SG\.[A-Za-z0-9_-]{22}\.[A-Za-z0-9_-]{43}|npm_[A-Za-z0-9]{36}|-----BEGIN ([A-Z]+ )?PRIVATE KEY-----'
content="$(printf '%s' "$input" | tr ',' '\n' | sed 's/\\n/\n/g')"
if printf '%s\n' "$content" | grep -E -- "$secret_re" | grep -vq 'guardrails:allow-secret'; then
  block "the content being written contains what looks like a real credential. Load secrets from environment/config instead; never commit them."
fi

exit 0
